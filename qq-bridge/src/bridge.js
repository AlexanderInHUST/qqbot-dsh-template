async function browserScreenshotV2(mcpUrl, tabIndex, lastPage = null) {
  const { Client } = await import('@modelcontextprotocol/sdk/client/index.js');
  const { StreamableHTTPClientTransport } = await import('@modelcontextprotocol/sdk/client/streamableHttp.js');
  const client = new Client({ name: 'qq-bridge-screenshot', version: '1' });
  await withTimeout(client.connect(new StreamableHTTPClientTransport(new URL(mcpUrl))), 15000, '连接浏览器');
  try {
    const listed = await withTimeout(client.callTool({ name: 'browser_tabs', arguments: { action: 'list' } }), 15000, '列标签页');
    const listText = (listed.content || []).filter((c) => c.type === 'text').map((c) => c.text).join('\n');
    const tabs = [...listText.matchAll(/^- (\d+):.*?\[(.*?)\]\((.*?)\)/gm)].map((m) => ({ index: Number(m[1]), title: m[2], url: m[3] }));
    const open = tabs.filter((t) => t.url && t.url !== 'about:blank');
    let tab;
    if (tabIndex !== undefined && tabIndex !== null && String(tabIndex).trim() !== '') {
      tab = tabs.find((t) => t.index === Number(tabIndex));
      if (!tab) throw new Error(`没有第 ${tabIndex} 个标签页（现在开着：${open.map((t) => `${t.index} ${t.title}`).join('；') || '没有'}）`);
    } else {
      // 默认截她正用着的那页（2026-10-23 前截的是最后一个不是 about:blank 的网页，
      // 她在 about:blank 上画的小游戏旁边开着 Poki，发出去的是 Poki）
      tab = pickScreenshotTab(tabs, lastPage);
      if (!tab) throw new Error('浏览器里没有打开的网页');
    }
    await withTimeout(client.callTool({ name: 'browser_tabs', arguments: { action: 'select', index: tab.index } }), 15000, '选标签页');
    const shot = await withTimeout(client.callTool({ name: 'browser_take_screenshot', arguments: { type: 'jpeg' } }), 30000, '截图');
    const image = (shot.content || []).find((c) => c.type === 'image' && c.data);
    if (!image) throw new Error('截图没有返回图片');
    return { tab, buffer: Buffer.from(image.data, 'base64'), mimeType: image.mimeType || 'image/jpeg' };
  } finally {
    await client.close().catch(() => {});
  }
}

function canonicalV2Key(key) {
  if (String(key ?? '').trim() === PLAY_KEY) return PLAY_KEY;
  const m = /^(group|private):(\d+)$/.exec(String(key ?? '').trim());
  if (!m) return null;
  const id = Number(m[2]);
  if (!Number.isSafeInteger(id) || id <= 0) return null;
  return `${m[1]}:${id}`;
}

