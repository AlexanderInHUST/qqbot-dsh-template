// 管理员 QQ（ownerQQ）规范化：空值=未设置；必须是正整数 QQ 号。
function normalizeOwnerQQ(value) {
  if (value === undefined || value === null) return null;
  const s = String(value).trim();
  if (!s) return null;
  if (!/^\d+$/.test(s)) throw new Error('ownerQQ 必须是 QQ 号（正整数）');
  const n = Number(s);
  if (!Number.isSafeInteger(n) || n <= 0) throw new Error('ownerQQ 必须是 QQ 号（正整数）');
  return n;
}

// qqbot_agent：主人可以不止一个。ownerQQ 是主人（系统提示只发给他）；extraOwnerQQ 里的人有同样的主人权限
// （管理命令、审批、夜里叫醒她、长期记忆里的叮嘱）。
function isOwnerId(cfg, id) {
  const s = String(id ?? '').trim();
  if (!s) return false;
  return s === String(cfg?.ownerQQ ?? '') || (cfg?.extraOwnerQQ ?? []).includes(s);
}

// qqbot_agent：主人们在她心里是谁（爸爸/妈妈…），写进消息上的管理员标记。{"QQ号": "称呼"}
function normalizeOwnerTitles(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return {};
  return Object.fromEntries(Object.entries(value)
    .map(([id, title]) => [String(id).trim(), String(title ?? '').trim().slice(0, 12)])
    .filter(([id, title]) => /^\d+$/.test(id) && title));
}

function ownerLabelFor(cfg, userId, key = '') {
  const id = String(userId ?? cfg?.ownerQQ ?? '');
  const title = cfg?.ownerTitles?.[id];
  // qqbot_agent：ownerTitlesGroups 配了就只在这些群里（和私聊里）带“你的爸爸”之类的称呼；
  // 别的群里标记本身就提醒她别这么叫（光靠人格卡压不住标记里的“你的爸爸”）
  // 没单独配 ownerTitlesGroups 时用 homeGroups：家里的群才叫爸爸妈妈
  const groups = cfg?.ownerTitlesGroups ?? cfg?.homeGroups;
  const m = /^group:(\d+)$/.exec(String(key));
  const outside = title && m && Array.isArray(groups) && !groups.includes(m[1]);
  // qqbot_agent：只写“主人”和称呼，不写“管理员”和 QQ 号：以前标记写“管理员（主人 QQ …）”，
  // 她就把自己当成有后台的机器人，跟群友说“得阿明在后台帮我换”。QQ 号在人格卡里有。
  if (outside) return `主人（这个群里叫他的名字，不叫${title}，也别提他是你${title}）`;
  return title ? `主人（你的${title}）` : '主人';
}

// 白名单/黑名单值规范化：只接受字符串或数字数组，非数组按空列表处理（fail-closed 语义由调用方决定）。
function normalizeIdList(value) {
  if (!Array.isArray(value)) return [];
  return value.map((v) => String(v).trim()).filter((v) => /^\d+$/.test(v));
}

