/**
 * qqbot_agent：按天存一份日志 state/logs/bridge-YYYY-MM-DD.log，每行带日期，留 LOG_KEEP_DAYS 天。
 * docker 的容器日志每次 force-recreate 就清空，bridge.log 2000 行一轮转（一天左右），
 * 以前查“前天几点发生了什么”什么都找不到。
 */
const DAILY_LOG_DIR = path.join(STATE_DIR, 'logs');
const LOG_KEEP_DAYS = Math.max(1, Number(process.env.BRIDGE_LOG_KEEP_DAYS) || 30);
let dailyLogDay = '';
function localDay(atMs = Date.now()) {
  const d = new Date(atMs);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}
function appendDailyLog(text) {
  try {
    const day = localDay();
    if (day !== dailyLogDay) {
      dailyLogDay = day;
      fs.mkdirSync(DAILY_LOG_DIR, { recursive: true });
      const cutoff = localDay(Date.now() - LOG_KEEP_DAYS * 86400000);
      for (const name of fs.readdirSync(DAILY_LOG_DIR)) {
        const m = /^bridge-(\d{4}-\d{2}-\d{2})\.log$/.exec(name);
        if (m && m[1] < cutoff) fs.rmSync(path.join(DAILY_LOG_DIR, name), { force: true });
      }
    }
    fs.appendFileSync(path.join(DAILY_LOG_DIR, `bridge-${day}.log`), text, 'utf8');
  } catch {}
}

function log(...args) {
  let line;
  try {
    const body = args
      .map((a) => redactSensitiveText(typeof a === 'string' ? a : JSON.stringify(a)))
      .join(' ')
      .replace(/[\r\n]+/g, ' ');
    line = `${localClock()} [bridge] ${body.length > LOG_LINE_MAX ? `${body.slice(0, LOG_LINE_MAX)}…[截断]` : body}`;
  } catch {
    line = `${localClock()} [bridge] (日志参数无法序列化)`;
  }
  // console.log 必须自成一个 try：stdout 的读者（守护窗口）消失时会抛 EPIPE，
  // 而 log() 是从 socket 事件回调里被调用的 —— 一旦抛出就会变成未捕获异常把进程带走。
  try { console.log(line); } catch {}
  appendBridgeLog(`${line}\n`);
  appendDailyLog(`${localDay().slice(5)} ${line}\n`);
}
